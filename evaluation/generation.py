import numpy as np


# ============================================================
# Stable softmax
# ============================================================

def stable_softmax(
    logits,
):
    """
    Numerically stable softmax for one
    vocabulary-logit vector.
    """

    logits = np.asarray(
        logits,
        dtype=np.float64,
    )

    maximum = np.max(
        logits
    )

    shifted = (
        logits
        -
        maximum
    )

    exponentials = np.exp(
        shifted
    )

    denominator = np.sum(
        exponentials
    )

    if (
        not np.isfinite(
            denominator
        )
        or
        denominator <= 0.0
    ):

        raise FloatingPointError(
            "Invalid softmax denominator."
        )

    probabilities = (
        exponentials
        /
        denominator
    )

    return probabilities


# ============================================================
# Top-k filtering
# ============================================================

def apply_top_k(
    logits,
    top_k,
):
    """
    Keep only the top-k largest logits.

    Everything else becomes -infinity.
    """

    logits = np.asarray(
        logits,
        dtype=np.float64,
    ).copy()

    if top_k is None:

        return logits

    top_k = int(
        top_k
    )

    if top_k <= 0:

        raise ValueError(
            "top_k must be positive."
        )

    vocabulary_size = (
        logits.shape[
            0
        ]
    )

    if (
        top_k
        >=
        vocabulary_size
    ):

        return logits

    cutoff_index = (
        vocabulary_size
        -
        top_k
    )

    top_indices = np.argpartition(
        logits,
        cutoff_index,
    )[
        cutoff_index:
    ]

    keep_mask = np.zeros(
        vocabulary_size,
        dtype=bool,
    )

    keep_mask[
        top_indices
    ] = True

    logits[
        ~keep_mask
    ] = -np.inf

    return logits


# ============================================================
# Top-p / nucleus filtering
# ============================================================

def apply_top_p(
    logits,
    top_p,
):
    """
    Keep the smallest set of tokens whose
    cumulative probability reaches top_p.

    Also called nucleus sampling.
    """

    logits = np.asarray(
        logits,
        dtype=np.float64,
    ).copy()

    if top_p is None:

        return logits

    top_p = float(
        top_p
    )

    if not (
        0.0
        <
        top_p
        <=
        1.0
    ):

        raise ValueError(
            "top_p must be in (0, 1]."
        )

    probabilities = (
        stable_softmax(
            logits
        )
    )

    sorted_indices = np.argsort(
        probabilities
    )[
        ::-1
    ]

    sorted_probabilities = (
        probabilities[
            sorted_indices
        ]
    )

    cumulative = np.cumsum(
        sorted_probabilities
    )

    # Remove tokens only AFTER the cumulative
    # probability has crossed top_p.
    remove_sorted = (
        cumulative
        >
        top_p
    )

    # Always keep the highest-probability token.
    remove_sorted[
        0
    ] = False

    # Shift mask one position so the token that
    # actually crosses the threshold is retained.
    if (
        len(
            remove_sorted
        )
        >
        1
    ):

        remove_sorted[
            1:
        ] = (
            remove_sorted[
                :-1
            ]
        )

        remove_sorted[
            0
        ] = False

    remove_indices = (
        sorted_indices[
            remove_sorted
        ]
    )

    logits[
        remove_indices
    ] = -np.inf

    return logits


# ============================================================
# Safe generation decode
# ============================================================

def safe_decode(
    tokenizer,
    token_ids,
):
    """
    Decode generated byte-level BPE tokens.

    Generation may occasionally stop in the
    middle of a multi-byte UTF-8 character.

    tokenizer.decode() is intentionally strict
    for corpus validation, but interactive
    generation should not crash because of an
    incomplete generated byte sequence.
    """

    special_token_ids = {
        tokenizer.pad_token_id,
        tokenizer.bos_token_id,
        tokenizer.eos_token_id,
    }

    chunks = []

    for token_id in token_ids:

        token_id = int(
            token_id
        )

        if (
            token_id
            in
            special_token_ids
        ):

            continue

        token_bytes = (
            tokenizer.token_bytes.get(
                token_id
            )
        )

        if token_bytes is None:

            continue

        chunks.append(
            token_bytes
        )

    byte_sequence = b"".join(
        chunks
    )

    return byte_sequence.decode(
        "utf-8",
        errors="replace",
    )


# ============================================================
# Select one token
# ============================================================

def select_next_token(
    logits,
    *,
    strategy,
    temperature,
    top_k,
    top_p,
    rng,
    forbidden_token_ids=None,
):
    """
    Choose one next token.

    Supported strategies:

        greedy
        sample
    """

    logits = np.asarray(
        logits,
        dtype=np.float64,
    ).copy()

    # ========================================================
    # Prevent special tokens we never want generated
    #
    # EOS is intentionally NOT forbidden.
    # ========================================================

    if (
        forbidden_token_ids
        is not None
    ):

        for token_id in (
            forbidden_token_ids
        ):

            logits[
                int(
                    token_id
                )
            ] = -np.inf

    # ========================================================
    # Greedy
    # ========================================================

    if strategy == "greedy":

        return int(
            np.argmax(
                logits
            )
        )

    if strategy != "sample":

        raise ValueError(
            "strategy must be "
            "'greedy' or 'sample'."
        )

    # ========================================================
    # Temperature
    # ========================================================

    temperature = float(
        temperature
    )

    if temperature <= 0.0:

        raise ValueError(
            "temperature must be positive."
        )

    logits = (
        logits
        /
        temperature
    )

    # ========================================================
    # Top-k
    # ========================================================

    logits = apply_top_k(
        logits,
        top_k,
    )

    # ========================================================
    # Top-p
    # ========================================================

    logits = apply_top_p(
        logits,
        top_p,
    )

    # ========================================================
    # Sample
    # ========================================================

    probabilities = (
        stable_softmax(
            logits
        )
    )

    if not np.all(
        np.isfinite(
            probabilities
        )
    ):

        raise FloatingPointError(
            "Non-finite sampling probabilities."
        )

    vocabulary_size = (
        probabilities.shape[
            0
        ]
    )

    next_token = rng.choice(
        vocabulary_size,
        p=probabilities,
    )

    return int(
        next_token
    )


# ============================================================
# Autoregressive generation
# ============================================================

def generate_text(
    *,
    model,
    tokenizer,
    prompt,
    max_new_tokens=50,
    strategy="sample",
    temperature=0.8,
    top_k=40,
    top_p=0.95,
    seed=42,
    stop_on_eos=True,
):
    """
    Autoregressively generate text.

    Process:

        prompt
          ↓
        tokenize
          ↓
        model forward
          ↓
        last-position logits
          ↓
        choose next token
          ↓
        append
          ↓
        repeat
    """

    if not isinstance(
        prompt,
        str,
    ):

        raise TypeError(
            "prompt must be a string."
        )

    max_new_tokens = int(
        max_new_tokens
    )

    if max_new_tokens <= 0:

        raise ValueError(
            "max_new_tokens must "
            "be positive."
        )

    rng = np.random.default_rng(
        seed
    )

    # ========================================================
    # Encode prompt
    # ========================================================

    prompt_token_ids = (
        tokenizer.encode(
            prompt,
            add_bos=False,
            add_eos=False,
        )
    )

    # Empty prompt needs something to begin from.
    if not prompt_token_ids:

        prompt_token_ids = [
            tokenizer.bos_token_id
        ]

    all_token_ids = list(
        prompt_token_ids
    )

    generated_token_ids = []

    stopped_on_eos = False

    # PAD and BOS should not appear as ordinary
    # generated continuation tokens.
    forbidden_token_ids = {
        tokenizer.pad_token_id,
        tokenizer.bos_token_id,
    }

    # ========================================================
    # Generate
    # ========================================================

    for _ in range(
        max_new_tokens
    ):

        # ----------------------------------------------------
        # Fixed model context window
        #
        # If generation grows beyond 256 tokens,
        # retain only the most recent context.
        # ----------------------------------------------------

        context_token_ids = (
            all_token_ids[
                -model.context_length:
            ]
        )

        input_ids = np.asarray(
            [
                context_token_ids
            ],
            dtype=np.int64,
        )

        # ----------------------------------------------------
        # Forward
        # ----------------------------------------------------

        logits = model.forward(
            input_ids
        )

        last_logits = (
            logits[
                0,
                -1,
                :
            ]
        )

        # ----------------------------------------------------
        # Decode one token
        # ----------------------------------------------------

        next_token_id = (
            select_next_token(
                last_logits,
                strategy=strategy,
                temperature=temperature,
                top_k=top_k,
                top_p=top_p,
                rng=rng,
                forbidden_token_ids=(
                    forbidden_token_ids
                ),
            )
        )

        # ----------------------------------------------------
        # EOS
        # ----------------------------------------------------

        if (
            next_token_id
            ==
            tokenizer.eos_token_id
        ):

            stopped_on_eos = True

            all_token_ids.append(
                next_token_id
            )

            generated_token_ids.append(
                next_token_id
            )

            if stop_on_eos:
                break

            continue

        all_token_ids.append(
            next_token_id
        )

        generated_token_ids.append(
            next_token_id
        )

    # ========================================================
    # Decode
    # ========================================================

    full_text = safe_decode(
        tokenizer,
        all_token_ids,
    )

    generated_text = safe_decode(
        tokenizer,
        generated_token_ids,
    )

    return {
        "prompt":
            prompt,

        "prompt_token_ids":
            prompt_token_ids,

        "generated_token_ids":
            generated_token_ids,

        "all_token_ids":
            all_token_ids,

        "generated_text":
            generated_text,

        "text":
            full_text,

        "generated_tokens":
            len(
                generated_token_ids
            ),

        "stopped_on_eos":
            stopped_on_eos,

        "strategy":
            strategy,

        "temperature":
            float(
                temperature
            ),

        "top_k":
            top_k,

        "top_p":
            top_p,

        "seed":
            int(
                seed
            ),
    }